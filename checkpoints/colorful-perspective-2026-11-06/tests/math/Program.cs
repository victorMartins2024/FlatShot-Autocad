using ColorFlatshot.Services;
int checks=0;
void Check(bool ok,string name){if(!ok)throw new Exception("FAIL "+name);Console.WriteLine("PASS "+name);checks++;}
bool Near(double a,double b)=>Math.Abs(a-b)<1e-8;
var matrix=new double[]{10,0,0,0,0,10,0,0,0,0,1,0,0,0,-1,10};
var camera=new PerspectiveCamera(matrix,new P3(0,0,10),new P3(0,0,-1),1,1,1,20);
Check(Near(camera.Project(new P3(2,1,0)).X,2),"target-plane scale");
Check(Near(camera.Project(new P3(2,1,5)).X,4),"near geometry grows with perspective");
Check(camera.Project(new P3(2,1,-10000)).Distance(new P2(0,0,0))<0.003,"vanishing point for parallel depth lines");
var a=new P3(0,0,11);var b=new P3(0,0,0);
Check(camera.ClipSegment(ref a,ref b)&&Near(a.Z,9),"clip crossing the camera near plane");
a=new P3(0,0,11);b=new P3(0,0,12);Check(!camera.ClipSegment(ref a,ref b),"reject geometry behind the eye");
a=new P3(0,0,-20);b=new P3(0,0,0);Check(camera.ClipSegment(ref a,ref b)&&Near(a.Z,-10),"far-plane clipping");
var polygon=camera.ClipPolygon(new[]{new P3(-1,0,11),new P3(1,0,0),new P3(0,1,0)});
Check(polygon.Count==4&&polygon.All(p=>camera.Depth(p)>=1-1e-8),"triangle near-plane clipping without exploding coordinates");
var tri=new ProjectedTriangle(new P2(-2,-1,.2),new P2(2,-1,.2),new P2(0,2,.2));
double lo,hi;
Check(tri.HiddenInterval(new P2(-4,0,.1),new P2(4,0,.1),0,out lo,out hi)&&Near(lo,1.0/3)&&Near(hi,2.0/3),"exact screen-space hidden interval");
Check(!tri.HiddenInterval(new P2(-4,0,.3),new P2(4,0,.3),0,out lo,out hi),"do not hide foreground edges");
Check(!tri.HiddenInterval(new P2(-4,0,.2),new P2(4,0,.2),0,out lo,out hi),"avoid self-occluding coplanar edges");
Check(tri.HiddenInterval(new P2(-4,0,.1),new P2(4,0,.3),0,out lo,out hi)&&Near(lo,1.0/3)&&Math.Abs(hi-.5)<1e-8,"perspective-correct inverse depth crossing");
var spans=new TriangleIndex(new[]{tri}).Classify(new P2(-4,0,.1),new P2(4,0,.1),0);
Check(spans.Count==3&&!spans[0].Hidden&&spans[1].Hidden&&!spans[2].Hidden,"visible-hidden-visible edge splitting");
var reversed=new ProjectedTriangle(tri.C,tri.B,tri.A);
Check(reversed.HiddenInterval(new P2(-4,0,.1),new P2(4,0,.1),0,out lo,out hi)&&Near(lo,1.0/3),"two-sided surface orientation");
var second=new ProjectedTriangle(new P2(-1,-1,.3),new P2(3,-1,.3),new P2(1,2,.3));
spans=new TriangleIndex(new[]{tri,second}).Classify(new P2(-4,0,.1),new P2(4,0,.1),0);
Check(spans.Count==3&&spans.Count(x=>x.Hidden)==1,"merge occlusion from multiple components");
var many=Enumerable.Range(0,50).Select(i=>new ProjectedTriangle(new P2(i*10,-1,.2),new P2(i*10+2,-1,.2),new P2(i*10+1,1,.2)));
Check(new TriangleIndex(many).Classify(new P2(-1,0,.1),new P2(3,0,.1),0).Any(x=>x.Hidden),"BVH lookup across many components");
Console.WriteLine($"ALL {checks} PERSPECTIVE MATH TESTS PASSED");
